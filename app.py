def xp_for_next_level(level):
    return 100 + (level - 1) * 50

def get_daily_thought(db, force=False):
    """Return the current mindset thought using a persistent scalable cursor.

    The cursor is stored in settings, so Mental Reset and the daily rotation use
    the exact same sequence. This avoids relying on dates or clearing hundreds
    of rows, and guarantees a thought is not repeated until the cursor has
    traversed the entire library. New thoughts are naturally picked up as the
    cursor moves forward.
    """
    today = date.today().isoformat()
    current = execute(db, 
        "SELECT value FROM settings WHERE key='thought_current_id'"
    ).fetchone()
    last_date = execute(db, 
        "SELECT value FROM settings WHERE key='thought_daily_date'"
    ).fetchone()

    current_id = int(current["value"]) if current and current["value"].isdigit() else None
    previous_date = last_date["value"] if last_date else None

    if current_id is None:
        row = execute(db, "SELECT * FROM thoughts ORDER BY id LIMIT 1").fetchone()
        if not row:
            return None
        current_id = row["id"]
        execute(db, 
            "INSERT INTO settings(key,value) VALUES('thought_current_id',%s) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (str(current_id),),
        )
        execute(db, 
            "INSERT INTO settings(key,value) VALUES('thought_daily_date',%s) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (today,),
        )
    elif previous_date != today:
        # New day: advance exactly once, then keep that thought for the day.
        next_row = execute(db, 
            "SELECT * FROM thoughts WHERE id>%s ORDER BY id LIMIT 1",
            (current_id,),
        ).fetchone()
        if next_row is None:
            next_row = execute(db, "SELECT * FROM thoughts ORDER BY id LIMIT 1").fetchone()
        if next_row:
            current_id = next_row["id"]
            execute(db, 
                "INSERT INTO settings(key,value) VALUES('thought_current_id',%s) "
                "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                (str(current_id),),
            )
        execute(db, 
            "INSERT INTO settings(key,value) VALUES('thought_daily_date',%s) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (today,),
        )

    row = execute(db, "SELECT * FROM thoughts WHERE id=%s", (current_id,)).fetchone()
    if row is None:
        # Recover cleanly if the selected thought was deleted.
        row = execute(db, "SELECT * FROM thoughts ORDER BY id LIMIT 1").fetchone()
        if row:
            execute(db, 
                "INSERT INTO settings(key,value) VALUES('thought_current_id',%s) "
                "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                (str(row["id"]),),
            )
    return row

def get_dashboard():
    with connect() as db:
        quests = execute(db, "SELECT * FROM quests ORDER BY completed ASC, id DESC").fetchall()
        evidence = execute(db, "SELECT * FROM evidence ORDER BY id DESC LIMIT 8").fetchall()
        settings = {r["key"]: r["value"] for r in execute(db, "SELECT * FROM settings")}
        account = execute(db, "SELECT email FROM users WHERE id=%s", (session.get("user_id"),)).fetchone()
        settings["account_email"] = account["email"] if account else ""
        all_completed = execute(db, "SELECT * FROM quests WHERE completed=1").fetchall()
        total_xp = sum(q["xp"] for q in all_completed)
        attrs = {name: 0 for name in ATTRIBUTES}
        for q in all_completed:
            attrs[q["attribute"]] = attrs.get(q["attribute"], 0) + q["xp"]
        # Each attribute point is earned XP scaled to keep bars readable.
        attr_scores = {k: min(100, int(v / 5)) for k, v in attrs.items()}
        level, remaining = 1, total_xp
        while remaining >= xp_for_next_level(level):
            remaining -= xp_for_next_level(level)
            level += 1
        need = xp_for_next_level(level)
        progress = int((remaining / need) * 100) if need else 0
        today = date.today().isoformat()
        completed_today = execute(db, 
            "SELECT COUNT(*) FROM quests WHERE completed=1 AND substr(completed_at,1,10)=%s", (today,)
        ).fetchone()[0]
        evidence_count = execute(db, "SELECT COUNT(*) FROM evidence").fetchone()[0]
        coding_total = execute(db, "SELECT COUNT(*) FROM coding_practice").fetchone()[0]
        coding_minutes = execute(db, "SELECT COALESCE(SUM(minutes),0) FROM coding_practice").fetchone()[0]
        coding_languages = execute(db, "SELECT COUNT(DISTINCT language) FROM coding_practice").fetchone()[0]
        coding_week = execute(db, 
            "SELECT COUNT(*) FROM coding_practice WHERE created_at >= %s",
            ((datetime.now() - timedelta(days=7)).isoformat(timespec="seconds"),)
        ).fetchone()[0]
        thought = get_daily_thought(db)
        recent_coding = execute(db, "SELECT * FROM coding_practice ORDER BY id DESC LIMIT 8").fetchall()
        favorites = execute(db, "SELECT * FROM thoughts WHERE is_favorite=1 ORDER BY id DESC").fetchall()
        all_thoughts = execute(db, "SELECT * FROM thoughts ORDER BY id DESC").fetchall()
        return {
            "quests": quests, "evidence": evidence, "settings": settings,
            "total_xp": total_xp, "level": level, "progress": progress,
            "xp_into_level": remaining, "xp_needed": need,
            "attrs": attr_scores, "raw_attrs": attrs,
            "completed_today": completed_today, "evidence_count": evidence_count,
            "daily_thought": thought, "favorite_thoughts": favorites, "all_thoughts": all_thoughts,
            "coding": {
                "total": coding_total, "minutes": coding_minutes, "languages": coding_languages,
                "week": coding_week, "recent": recent_coding
            }
        }

