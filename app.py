@app.route("/setup", methods=["GET", "POST"])
def setup():
    with connect() as db:
        exists = execute(db, "SELECT COUNT(*) FROM users").fetchone()[0] > 0
    if exists:
        return redirect(url_for("login"))
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")
        confirm = request.form.get("confirm_password", "")
        if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
            flash("Enter a valid email address.", "error")
        elif len(password) < 8:
            flash("Use a password with at least 8 characters.", "error")
        elif password != confirm:
            flash("Passwords do not match.", "error")
        else:
            with connect() as db:
                execute(db, "INSERT INTO users(email,password_hash,created_at) VALUES(%s,%s,%s)",
                    (email, generate_password_hash(password), datetime.now().isoformat(timespec="seconds")))
                session.clear()
                session["user_id"] = execute(db, "SELECT id FROM users WHERE LOWER(email)=LOWER(%s)", (email,)).fetchone()["id"]
            flash("Your account is ready. Welcome to Reality RPG!", "success")
            return redirect(url_for("index"))
    return render_template("auth.html", mode="setup")

