class HybridRow(dict):
    """Provides both SQLite-style numeric and name-based row access."""
    def __init__(self, description, values):
        self._values = tuple(values)
        super().__init__((col.name, value) for col, value in zip(description, values))
    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)

class HybridCursor:
    def __init__(self, cursor):
        self.cursor = cursor
    def fetchone(self):
        row = self.cursor.fetchone()
        return HybridRow(self.cursor.description, row) if row is not None else None
    def fetchall(self):
        return [HybridRow(self.cursor.description, row) for row in self.cursor.fetchall()]
    def __iter__(self):
        return iter(self.fetchall())

def execute(db, sql, params=None):
    cursor = db.cursor()
    cursor.execute(sql, params or ())
    return HybridCursor(cursor)

def executemany(db, sql, params_seq):
    cursor = db.cursor()
    cursor.executemany(sql, params_seq)
    cursor.close()

