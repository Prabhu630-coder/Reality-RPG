@app.post("/thought/next")
def next_thought():
    """Mental Reset: advance to the next thought in the persistent rotation.

    Uses one indexed id lookup rather than loading the whole library, so the
    same logic remains fast for hundreds or thousands of thoughts. The current
    thought is never selected again until the cursor wraps past the final id.
    """
    with connect() as db:
        current = execute(db, 
            "SELECT value FROM settings WHERE key='thought_current_id'"
        ).fetchone()
        total = execute(db, "SELECT COUNT(*) AS n FROM thoughts").fetchone()["n"]
        if not total:
            flash("Add a thought to your mindset library first.", "error")
            return redirect(url_for("index") + "#mindset")

        current_id = int(current["value"]) if current and current["value"].isdigit() else 0
        chosen = execute(db, 
            "SELECT * FROM thoughts WHERE id>%s ORDER BY id LIMIT 1",
            (current_id,),
        ).fetchone()
        if chosen is None:
            chosen = execute(db, "SELECT * FROM thoughts ORDER BY id LIMIT 1").fetchone()

        execute(db, 
            "INSERT INTO settings(key,value) VALUES('thought_current_id',%s) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (str(chosen["id"]),),
        )
        execute(db, 
            "INSERT INTO settings(key,value) VALUES('thought_daily_date',%s) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (date.today().isoformat(),),
        )
        flash("Mental reset: next thought loaded.", "success")
    return redirect(url_for("index") + "#mindset")

