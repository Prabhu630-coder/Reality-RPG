def github_api_json(url, token, timeout=15):
    """GET JSON from GitHub's authenticated REST API."""
    headers = {
        "User-Agent": "Reality-RPG/1.0",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2026-03-10",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def github_commit_evidence_exists(db, sha):
    return execute(db, 
        "SELECT COUNT(*) FROM evidence WHERE kind='github' AND details LIKE %s",
        (f"%commit:{sha}%",),
    ).fetchone()[0] > 0


@app.post("/github/sync")
def github_sync():
    """Sync GitHub from authenticated repositories/commits, not public events.

    Public Events can lag by hours and do not reliably expose private repositories.
    This route uses the authenticated REST API to enumerate repositories the token
    can access, then reads recent commits from each repository.
    """
    with connect() as db:
        settings = {r["key"]: r["value"] for r in execute(db, "SELECT * FROM settings")}

    username = settings.get("github_username", "").strip()
    token = os.environ.get("GITHUB_TOKEN", "").strip()
    if not token:
        flash("Add a GitHub personal access token in Settings to enable reliable authenticated sync, including private repositories.", "error")
        return redirect(url_for("index"))

    try:
        # 1) Authenticate the token and use GitHub's canonical username.
        me = github_api_json("https://api.github.com/user", token)
        api_username = (me.get("login") or "").strip()
        if not api_username:
            flash("GitHub authentication succeeded but no GitHub username was returned.", "error")
            return redirect(url_for("index"))

        # Keep the user-entered username synchronized, but don't use it as the
        # authority for repository access. The token is the authority.
        if api_username != username:
            username = api_username
            with connect() as db:
                execute(db, "INSERT INTO settings(key,value) VALUES('github_username',%s) ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value", (username,))

        # 2) Get repositories the authenticated user can access, including private repos.
        repos = github_api_json(
            "https://api.github.com/user/repos?visibility=all&affiliation=owner,collaborator,organization_member&sort=pushed&direction=desc&per_page=100",
            token,
        )
        if not isinstance(repos, list):
            raise ValueError("Unexpected repository response from GitHub")

        # 3) Look back far enough to catch commits made since the last sync.
        # On the first sync, inspect the latest commits in each recently pushed repo.
        last_sync = settings.get("github_last_sync", "").strip()
        try:
            last_sync_dt = datetime.fromisoformat(last_sync) if last_sync else None
        except ValueError:
            last_sync_dt = None

        discovered = []
        checked_repos = 0
        for repo in repos:
            full_name = repo.get("full_name")
            if not full_name or repo.get("archived") or repo.get("disabled"):
                continue

            # Avoid hammering the API on an initial sync: the API returns the
            # newest 10 commits for each of the 100 most recently pushed repos.
            # For subsequent syncs, only repositories pushed after last sync are
            # queried, with a small safety window for timestamp differences.
            pushed_at = repo.get("pushed_at") or ""
            if last_sync_dt and pushed_at:
                try:
                    pushed_dt = datetime.fromisoformat(pushed_at.replace("Z", "+00:00")).replace(tzinfo=None)
                    if pushed_dt < (last_sync_dt - timedelta(minutes=10)):
                        continue
                except ValueError:
                    pass

            commits_url = f"https://api.github.com/repos/{full_name}/commits?per_page=20"
            commits = github_api_json(commits_url, token)
            if not isinstance(commits, list):
                continue
            checked_repos += 1

            for commit in commits:
                sha = commit.get("sha")
                commit_info = commit.get("commit") or {}
                author = commit_info.get("author") or {}
                committed_at = author.get("date") or ""
                if not sha:
                    continue

                # On later syncs, stop once commits are older than the last sync.
                if last_sync_dt and committed_at:
                    try:
                        commit_dt = datetime.fromisoformat(committed_at.replace("Z", "+00:00")).replace(tzinfo=None)
                        if commit_dt <= last_sync_dt:
                            continue
                    except ValueError:
                        pass

                discovered.append({
                    "sha": sha,
                    "repo": full_name,
                    "message": (commit_info.get("message") or "Commit").splitlines()[0][:160],
                    "author": (author.get("name") or "Unknown"),
                    "date": committed_at,
                    "url": commit.get("html_url") or f"https://github.com/{full_name}/commit/{sha}",
                })

        # Oldest -> newest gives a natural evidence history and lets each new
        # commit complete at most one pending coding quest.
        discovered.sort(key=lambda x: x.get("date") or "")

        new_commits = []
        with connect() as db:
            for item in discovered:
                if github_commit_evidence_exists(db, item["sha"]):
                    continue
                title = f"GitHub commit: {item['repo']}"
                details = (
                    f"commit:{item['sha']} · {item['message']} · "
                    f"author:{item['author']} · {item['date']} · {item['url']}"
                )
                awarded = award_matching_quests(db, "coding", title, details)
                execute(db, 
                    "UPDATE evidence SET kind='github' WHERE id=(SELECT MAX(id) FROM evidence)"
                )
                new_commits.append((item, awarded))

            execute(db, 
                "INSERT INTO settings(key,value) VALUES('github_last_sync',%s)",
                (datetime.now().isoformat(timespec="seconds"),),
            )

        if not new_commits:
            flash(
                f"GitHub sync complete. Checked {checked_repos} accessible repositories; no new commits were found.",
                "success",
            )
            return redirect(url_for("index"))

        awarded_xp = sum(a[0]["xp"] for _, a in new_commits if a)
        private_count = sum(1 for item, _ in new_commits if any(
            r.get("full_name") == item["repo"] and r.get("private") for r in repos
        ))
        summary = f"GitHub sync found {len(new_commits)} new commit(s) across {checked_repos} repositories."
        if private_count:
            summary += f" {private_count} came from private repositories."
        if awarded_xp:
            summary += f" +{awarded_xp} XP awarded through coding quests."
        flash(summary, "success")

    except urllib.error.HTTPError as e:
        try:
            body = e.read().decode("utf-8", errors="replace")
            api_error = json.loads(body).get("message", "")
        except Exception:
            api_error = ""
        if e.code == 401:
            message = "GitHub authentication failed. Check that your token is valid and has the required repository access."
        elif e.code == 403:
            message = "GitHub denied the request. Check token permissions/rate limits and repository access."
        else:
            message = f"GitHub returned HTTP {e.code}."
        if api_error:
            message += f" {api_error}"
        flash(message, "error")
    except (urllib.error.URLError, TimeoutError):
        flash("Could not reach GitHub right now. Check your connection and try again.", "error")
    except (ValueError, json.JSONDecodeError) as e:
        flash(f"GitHub sync could not read the API response: {e}", "error")

    return redirect(url_for("index"))

